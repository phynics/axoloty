import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const MODULES = Object.freeze({
  AxolotyWire: "Packages/AxolotyWire/Sources/AxolotyWire",
  AxolotyProtocol: "Packages/AxolotyProtocol/Sources/AxolotyProtocol",
});

const sha256 = value => crypto.createHash("sha256").update(value).digest("hex");

function fail(message) {
  throw new Error(message);
}

function canonicalPath(root, value, directory = root) {
  const absolute = path.resolve(directory, value);
  const relative = path.relative(root, absolute);
  if (!relative || relative.startsWith(".." + path.sep) || path.isAbsolute(relative)) {
    fail(`compiler input is outside the repository: ${value}`);
  }
  return relative.split(path.sep).join("/");
}

function commandArguments(entry) {
  if (Array.isArray(entry.arguments)) return entry.arguments.map(String);
  if (typeof entry.command !== "string") return [];
  // compile_commands.json generated by SwiftPM/CMake normally includes simple
  // quoted paths. Preserve the command spelling for the digest while using the
  // declared `file` field as the source identity.
  return entry.command.match(/(?:[^\s"']+|"[^"]*"|'[^']*')+/g) ?? [];
}

function loadCommands(file) {
  let value;
  try {
    value = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    fail(`unable to decode compile command database ${file}: ${error.message}`);
  }
  if (!Array.isArray(value)) fail(`compile command database must be an array: ${file}`);
  return value;
}

export function emit({ root, buildSystem, targetTriple, compilerIdentity, commandsFile }) {
  if (!["swiftpm", "esp-idf-cmake"].includes(buildSystem)) fail(`unsupported build system: ${buildSystem}`);
  if (!targetTriple || !compilerIdentity) fail("targetTriple and compilerIdentity are required");
  const commands = loadCommands(commandsFile);
  const sourcesByModule = new Map(Object.keys(MODULES).map(name => [name, new Map()]));
  const argumentVector = [];
  for (const entry of commands) {
    if (!entry || typeof entry.file !== "string") continue;
    const relative = canonicalPath(root, entry.file, typeof entry.directory === "string" ? entry.directory : root);
    if (!relative.endsWith(".swift")) continue;
    argumentVector.push({ file: relative, arguments: commandArguments(entry) });
    for (const [module, sourceRoot] of Object.entries(MODULES)) {
      if (relative === sourceRoot || relative.startsWith(`${sourceRoot}/`)) {
        if (!fs.existsSync(path.join(root, relative))) fail(`compiler input is missing: ${relative}`);
        sourcesByModule.get(module).set(relative, sha256(fs.readFileSync(path.join(root, relative))));
      }
    }
  }
  if (argumentVector.length === 0) fail("compile command database contains no Swift compiler inputs");
  const modules = [...sourcesByModule].map(([module, sources]) => {
    if (sources.size === 0) fail(`compile command database contains no input for ${module}`);
    return {
      module,
      sources: [...sources].sort(([left], [right]) => left.localeCompare(right)).map(([file, digest]) => ({ path: file, sha256: digest })),
    };
  });
  return {
    schemaVersion: 1,
    buildSystem,
    targetTriple,
    compilerIdentity,
    compilerArgumentsDigest: sha256(JSON.stringify(argumentVector.sort((left, right) => left.file.localeCompare(right.file)))),
    modules,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [root, buildSystem, targetTriple, compilerIdentity, commandsFile, output] = process.argv.slice(2);
  if (![root, buildSystem, targetTriple, compilerIdentity, commandsFile, output].every(Boolean)) {
    console.error("usage: emit-g6-source-receipt.mjs <root> <swiftpm|esp-idf-cmake> <target-triple> <compiler> <compile_commands.json> <output>");
    process.exit(64);
  }
  try {
    fs.writeFileSync(output, `${JSON.stringify(emit({ root: path.resolve(root), buildSystem, targetTriple, compilerIdentity, commandsFile: path.resolve(commandsFile) }))}\n`);
  } catch (error) {
    console.error(`G6 SOURCE RECEIPT EMIT FAIL: ${error.message}`);
    process.exit(1);
  }
}
